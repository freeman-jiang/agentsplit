// Generates db/schema/auth.ts from Better Auth's own table definitions for the
// plugin set in src/server/auth/auth-options.ts. Run after upgrading Better Auth:
//   bun scripts/gen-auth-schema.ts
import { writeFileSync } from 'node:fs'
import { getSchema } from 'better-auth/db'
import { authPlugins } from '../src/server/auth/auth-options'

type Field = {
  type: string | string[]
  required?: boolean
  unique?: boolean
  fieldName?: string
  references?: { model: string; field: string; onDelete?: string }
  defaultValue?: unknown
  index?: boolean
  bigint?: boolean
}

const schema = getSchema({ plugins: authPlugins(), rateLimit: { storage: 'database' } }) as Record<
  string,
  { fields: Record<string, Field> }
>

/**
 * Rules of v1's schema that getSchema() does not declare: unique
 * keys (P-DB-115, P-DB-116, P-DB-121) and the owner of an API key (P-DB-117).
 * Keys are model and field names as getSchema() gives them.
 */
const EXTRA: Record<string, { unique?: string[][]; references?: Record<string, NonNullable<Field['references']>> }> = {
  account: { unique: [['providerId', 'accountId']] },
  apikey: { unique: [['key']], references: { referenceId: { model: 'user', field: 'id', onDelete: 'cascade' } } },
  oauthClientResource: { unique: [['clientId', 'resourceId']] },
}

const snake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`).replace(/^_/, '')
const camel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase())

const column = (field: Field) => {
  switch (field.type) {
    case 'string':
      return 'text()'
    case 'number':
      return field.bigint ? "bigint({ mode: 'number' })" : 'integer()'
    case 'boolean':
      return 'boolean()'
    case 'date':
      return "timestamp({ withTimezone: true, mode: 'date' })"
    case 'json':
      return 'jsonb()'
    case 'string[]':
      return 'text().array()'
    case 'number[]':
      return 'integer().array()'
    default:
      throw new Error(`Unmapped Better Auth field type: ${JSON.stringify(field.type)}`)
  }
}

const tables = Object.entries(schema).map(([modelName, table]) => ({ modelName, ...table }))
const byModel = new Map(tables.map((t) => [t.modelName, t]))
const lines = [
  '// Generated by scripts/gen-auth-schema.ts from Better Auth getSchema(). Do not edit.',
  "import { bigint, boolean, index, integer, jsonb, pgTable, text, timestamp, unique } from 'drizzle-orm/pg-core'",
  '',
]
for (const table of tables) {
  const name = camel(table.modelName)
  lines.push(`export const ${name} = pgTable(`, `  '${snake(table.modelName)}',`, '  {', "    id: text().primaryKey(),")
  const extra = EXTRA[table.modelName] ?? {}
  const keys = (extra.unique ?? []).filter((columns) => columns.length > 1)
  const single = new Set((extra.unique ?? []).filter((columns) => columns.length === 1).flat())
  const indexes: string[] = []
  for (const [key, given] of Object.entries(table.fields)) {
    const references = extra.references?.[key]
    const field: Field = { ...given, ...(references ? { references } : {}), ...(single.has(key) ? { unique: true } : {}) }
    const prop = camel(field.fieldName ?? key)
    let def = column(field)
    if (field.required) def += '.notNull()'
    if (field.unique) def += '.unique()'
    if (Array.isArray(field.defaultValue) && field.defaultValue.length === 0) def += '.default([])'
    else if (typeof field.defaultValue === 'boolean' || typeof field.defaultValue === 'number')
      def += `.default(${JSON.stringify(field.defaultValue)})`
    else if (typeof field.defaultValue === 'string') def += `.default(${JSON.stringify(field.defaultValue)})`
    if (field.references) {
      const target = byModel.get(field.references.model)
      if (!target) throw new Error(`Unknown reference ${field.references.model}`)
      const onDelete = field.references.onDelete ?? 'cascade'
      def += `.references(() => ${camel(target.modelName)}.${camel(field.references.field)}, { onDelete: '${onDelete}' })`
    }
    // A unique column has its own index.
    if ((field.index || field.references) && !field.unique) indexes.push(prop)
    lines.push(`    ${prop}: ${def},`)
  }
  lines.push('  },')
  const constraints = [
    ...indexes.map((p) => `index().on(t.${p})`),
    ...keys.map((columns) => `unique().on(${columns.map((c) => `t.${camel(c)}`).join(', ')})`),
  ]
  if (constraints.length) lines.push(`  (t) => [${constraints.join(', ')}],`)
  lines.push(')', '')
}
writeFileSync(new URL('../db/schema/auth.ts', import.meta.url), lines.join('\n'))
console.log(tables.map((t) => `${t.modelName}: ${Object.keys(t.fields).length} fields`).join('\n'))
